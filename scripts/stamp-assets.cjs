#!/usr/bin/env node
/* One version, automatic cache-busting.
 *  - every local "file.js?v=…" / "file.css?v=…" reference in trainer.js, app.js,
 *    index.html and sw.js gets ?v=<content hash>, so a changed file always gets a new URL;
 *  - index.html scripts/styles without ?v get one;
 *  - the service worker's precache list and cache name are regenerated from those URLs;
 *  - the visible version (data-mono-version) comes from package.json.
 * Run `node scripts/stamp-assets.cjs` after editing front-end files.
 * `--check` changes nothing and exits 1 when something is stale (used by the tests). */
'use strict';
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const ROOT = path.join(__dirname, '..');
const CHECK = process.argv.includes('--check');
const read = f => fs.readFileSync(path.join(ROOT, f), 'utf8');
const exists = f => { try { return fs.statSync(path.join(ROOT, f)).isFile(); } catch { return false; } };
const hash = f => crypto.createHash('sha256').update(fs.readFileSync(path.join(ROOT, f))).digest('hex').slice(0, 10);
const version = JSON.parse(read('package.json')).version;
const shortVersion = 'v' + version.split('.').slice(0, 2).join('.');

const REF = /((?:\.\/)?)((?:vendor\/|icons\/)?[A-Za-z0-9_.-]+\.(?:js|css))\?v=([A-Za-z0-9._-]+)/g;
const stampRefs = text => text.replace(REF, (m, pre, file) => exists(file) ? `${pre}${file}?v=${hash(file)}` : m);

function stampIndex(text) {
  text = text.replace(/((?:src|href)=")((?:vendor\/)?[A-Za-z0-9_.-]+\.(?:js|css))(")/g, (m, a, file, b) => exists(file) ? `${a}${file}?v=${hash(file)}${b}` : m);
  return stampRefs(text).replace(/(<span data-mono-version>)[^<]*(<\/span>)/g, `$1${shortVersion}$2`);
}

function assetList(files) {
  const refs = new Set();
  const index = files['index.html'];
  for (const m of index.matchAll(/(?:src|href)="((?:vendor\/)?[A-Za-z0-9_.-]+\.(?:js|css)\?v=[A-Za-z0-9._-]+)"/g)) refs.add('./' + m[1]);
  for (const f of ['app.js', 'trainer.js', 'sw.js'])
    for (const m of files[f].matchAll(REF)) if (exists(m[2])) refs.add('./' + m[2] + '?v=' + m[3]);
  const icons = fs.readdirSync(path.join(ROOT, 'icons')).filter(f => f.endsWith('.svg')).sort().map(f => './icons/' + f);
  const fixed = ['./', './index.html', './manifest.webmanifest', './icon.svg', './app-icon-192.png', './app-icon-512.png', './vendor/leaflet.js', './vendor/leaflet.css'];
  return [...fixed, ...[...refs].sort(), ...icons];
}

function stampSw(text, files) {
  const assets = assetList(files);
  const cache = `mono-weather-${version}-` + crypto.createHash('sha256').update(JSON.stringify(assets)).digest('hex').slice(0, 8);
  const block = `/* ASSETS:BEGIN — generated by scripts/stamp-assets.cjs, do not edit by hand */\nconst CACHE = '${cache}';\nconst ASSETS = ${JSON.stringify(assets, null, 0).replace(/","/g, '", "')};\n/* ASSETS:END */`;
  return text.replace(/\/\* ASSETS:BEGIN[\s\S]*?\/\* ASSETS:END \*\//, block);
}

const ORDER = ['trainer.js', 'app.js', 'index.html', 'sw.js'];
const original = Object.fromEntries(ORDER.map(f => [f, read(f)]));
const files = { ...original };
// Files reference each other (index → app.js → trainer.js → model.js); iterate to a fixed point.
// In --check mode the stamped text lives in memory only, so hashes of edited files are computed
// from disk; that is exactly the question --check answers: "is what is on disk consistent?".
for (let pass = 0; pass < 6; pass++) {
  let changed = false;
  for (const f of ORDER) {
    const next = f === 'index.html' ? stampIndex(files[f]) : f === 'sw.js' ? stampSw(stampRefs(files[f]), files) : stampRefs(files[f]);
    if (next !== files[f]) { files[f] = next; changed = true; if (!CHECK) fs.writeFileSync(path.join(ROOT, f), next); }
  }
  if (!changed) break;
}
const stale = ORDER.filter(f => files[f] !== original[f]);
if (CHECK) {
  if (stale.length) { console.error('Stale asset versions in: ' + stale.join(', ') + '. Run: node scripts/stamp-assets.cjs'); process.exit(1); }
  console.log('Asset versions are up to date (' + version + ').');
} else console.log(stale.length ? 'Stamped: ' + stale.join(', ') : 'Nothing to stamp.', '· version', version);
module.exports = { assetList };
